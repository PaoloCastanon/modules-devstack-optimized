CREATE TABLE image_data_operations (
    image_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
    attempt_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    phase VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    expected_size BIGINT NULL,
    size BIGINT NULL,
    virtual_size BIGINT NULL,
    checksum CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    os_hash_value CHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
    cleanup_target VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NULL,
    last_error_code VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    CONSTRAINT data_operation_image_fk FOREIGN KEY (image_id) REFERENCES images(id),
    UNIQUE KEY data_operation_attempt (attempt_id),
    INDEX data_operation_reconcile (phase, updated_at, image_id),
    CONSTRAINT data_operation_phase CHECK (phase IN ('reserved','staged','published','committed','cleanup','cleaned')),
    CONSTRAINT data_operation_sizes CHECK ((expected_size IS NULL OR expected_size >= 0) AND (size IS NULL OR size >= 0) AND (virtual_size IS NULL OR virtual_size >= 0)),
    CONSTRAINT data_operation_cleanup CHECK ((cleanup_target IS NULL OR cleanup_target IN ('queued','deleted','killed')) AND (phase NOT IN ('cleanup','cleaned') OR cleanup_target IS NOT NULL)),
    CONSTRAINT data_operation_receipt CHECK (phase NOT IN ('staged','published','committed') OR (size IS NOT NULL AND checksum IS NOT NULL AND os_hash_value IS NOT NULL)),
    CONSTRAINT data_operation_md5 CHECK (checksum IS NULL OR REGEXP_LIKE(checksum, '^[0-9a-f]{32}$', 'c')),
    CONSTRAINT data_operation_sha512 CHECK (os_hash_value IS NULL OR REGEXP_LIKE(os_hash_value, '^[0-9a-f]{128}$', 'c')),
    CONSTRAINT data_operation_error CHECK (last_error_code IS NULL OR last_error_code IN ('interrupted','invalid_size','size_limit','store_full','store_io','integrity','cancelled','recovery','deleted','terminal'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin;
